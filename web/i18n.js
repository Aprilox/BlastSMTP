const LANG_KEY = 'blastsmtp.lang';

/** Current language, restored from the last choice or guessed from the browser. */
let lang = (() => {
  try {
    const saved = localStorage.getItem(LANG_KEY);
    if (saved && STRINGS[saved]) return saved;
  } catch { /* private browsing: fall through to the browser hint */ }
  return (navigator.language || 'en').toLowerCase().startsWith('fr') ? 'fr' : 'en';
})();

/** t returns the translated string for key, substituting {0}, {1}… positionally. */
function t(key, ...args) {
  const table = STRINGS[lang] || STRINGS.en;
  let s = table[key];
  if (s === undefined) s = STRINGS.en[key];
  if (s === undefined) return key; // visible on screen, so a miss is obvious
  return s.replace(/\{(\d+)\}/g, (m, i) => (args[i] !== undefined ? String(args[i]) : m));
}

function currentLang() {
  return lang;
}

/** applyI18n rewrites every element carrying a data-i18n* attribute. */
function applyI18n(root = document) {
  root.querySelectorAll('[data-i18n]').forEach((el) => {
    el.textContent = t(el.dataset.i18n);
  });
  root.querySelectorAll('[data-i18n-html]').forEach((el) => {
    el.innerHTML = t(el.dataset.i18nHtml);
  });
  root.querySelectorAll('[data-i18n-ph]').forEach((el) => {
    el.placeholder = t(el.dataset.i18nPh);
  });
  root.querySelectorAll('[data-i18n-title]').forEach((el) => {
    el.title = t(el.dataset.i18nTitle);
  });
  document.documentElement.lang = lang;
  document.title = t('doc.title');
}

/** setLang switches language and lets the app re-render its dynamic parts. */
function setLang(next) {
  if (!STRINGS[next] || next === lang) return;
  lang = next;
  try {
    localStorage.setItem(LANG_KEY, lang);
  } catch { /* not persisting is survivable */ }
  applyI18n();
  document.querySelectorAll('#lang-seg button').forEach((b) => {
    b.classList.toggle('on', b.dataset.lang === lang);
  });
  window.dispatchEvent(new CustomEvent('langchange', { detail: lang }));
}
